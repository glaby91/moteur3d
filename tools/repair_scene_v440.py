#!/usr/bin/env python3
"""V17.440 — independent audit/repair of REAL V17.439 (V8) resources.

Only touches newly named 440 resource files; preserved art/radio and original
V8 and V439 files are not overwritten. Every fix has a named diagnostic.
"""
import argparse, copy, hashlib, json, math
from pathlib import Path
F='Architecture/Palais/'
P='Interieur/Piscine olympique/'
G='Interieur/Galeries/'
def load(p):return json.loads(Path(p).read_text(encoding='utf-8-sig'))
def write(p,v):
    p=Path(p);p.parent.mkdir(parents=True,exist_ok=True)
    p.write_text(json.dumps(v,ensure_ascii=False,separators=(',',':'))+'\n',encoding='utf-8')
def box(n,p,pos,size,mat):
    return dict(id=n,parent=p,geometry='unit_box',position=list(pos),size=list(size),
                material=mat,rotationY=0)
def aabb(o):
    x,y,z=o['position'];w,h,d=o['size']
    return x-w/2,x+w/2,y-h/2,y+h/2,z-d/2,z+d/2
def xy_overlap(a,b):
    aa=aabb(a);bb=aabb(b)
    return min(aa[1],bb[1])-max(aa[0],bb[0]),min(aa[5],bb[5])-max(aa[4],bb[4])
def build(root):
    root=Path(root)
    scene=load(root/'scene-v7-corrections.json')
    sec=scene['sectors'][0]
    assert 'v439' in sec['instances'][0],sec['instances']
    inp=load(root/sec['instances'][0]);objs=inp['instances']
    mp=load(root/sec['materials'][0]);pbr=load(root/sec['pbr'][0])
    mgeo=root/'geometry/revision-v439-entry-design.json';geo=load(mgeo)
    assert len(geo['meshes'])==1
    mesh=geo['meshes'][0]
    assert mesh['id']=='v439_entry_mosaic_trapezoid'
    originalArt=root/'textures/revision/v439/cse_parvis_mosaique.png'
    newArt=root/'textures/revision/v440/cse_parvis_mosaique.png'
    assert originalArt.exists() and newArt.exists()
    originals={str(p.relative_to(root)):hashlib.sha256(p.read_bytes()).hexdigest()
       for p in root.glob('textures/**/*energetik*fresco*.jpg')}
    assert originals,'Fresco integrity check requires genuine image'
    report=dict(version='V17.440',source='V17.439/V8',issues={},counts={},
                validations=[],frescoHash=originals)
    ids={o['id'] for o in objs}
    def add(o):
        assert o['id'] not in ids,o['id']
        ids.add(o['id']);objs.append(o)
    def remove(pred,name):
        nonlocal objs
        kept=[];n=0
        for o in objs:
            if pred(o):n+=1
            else:kept.append(o)
        objs=kept;report['counts'][name]=n
        return n

    # A14, R1 — previous "double-sided" mosaic drew opposite face triangles
    # on the EXACT SAME depth plane (4 instead of 2), generating flickering.
    assert len(mesh['faces'])==4,mesh['faces']
    assert mesh['faces'][0]==[0,2,1] and mesh['faces'][1]==[0,3,2]
    mesh['faces']=mesh['faces'][:2]
    # Both triangles normal +Y. Retain authored tessera graphic, use coarse
    # tiles and low-frequency contours in the new PNG generated by Node.
    geo440='geometry/revision-v440-entry-mosaic-single-surface.json'
    write(root/geo440,dict(format='m3d-geometry-v1',units='m',meshes=[mesh]))
    for o in objs:
        if o['id']=='v439_entry_mosaic_art':
            o['geometry']='v440_entry_mosaic'
    mesh['id']='v440_entry_mosaic'
    write(root/geo440,dict(format='m3d-geometry-v1',units='m',meshes=[mesh]))
    sec['geometry']=[p for p in sec['geometry'] if p!='geometry/revision-v439-entry-design.json']+[geo440]
    assert all(len(m['faces'])==2 for m in load(root/geo440)['meshes'])
    pbrMat=next(p for p in pbr['sets'] if p['id']=='tex_v439_entry_art')
    pbrMat['imageFile']='textures/revision/v440/cse_parvis_mosaique.png'
    pbrMat['resolution']=512
    report['issues']['14_mosaic']='single up-facing mesh; simplified original tesserae; 512px with mipmaps'

    # A1/A2: historical V8 intentionally generated a rail across the
    # still-existing main hall staircase at z=-13.7. Remove the 7 specifically
    # documented closure objects, keeping all normal handrails and guardrails.
    n=remove(lambda o:o['id'].startswith(('v8_former_hall_stair_closure_','v8_hall_old_stair_post_')),
             '02_hall_stair_rail_blockers_removed')
    assert n==7,('Expected 7 documented stair closure primitives',n)
    report['issues']['02_hall_stairs']='removed 7 obsolete railing closure elements; V8 flights retained'

    # A3, A5, A12: restore a shared facade datum. Trim ONLY front cantilever
    # beams extending outside glass, keeping their structural columns,
    # curtain wall and skylight. Keep a small support inside the facade.
    beamFix=0
    for o in objs:
        if o['parent']!=F+'Poutres' or o['geometry']!='unit_box':continue
        if o['position'][1]<12 or o['size'][2]<7:continue
        lo,hi=aabb(o)[4:6]
        if hi> -4.55 and lo< -4.55:
            o['size'][2]=round(-4.55-lo,5)
            o['position'][2]=round((lo-4.55)/2,5)
            beamFix+=1
    report['counts']['05_cantilever_beams_trimmed']=beamFix
    report['issues']['03_05_12_facade']='front beam limits stop behind glass plane; outer concrete and columns retained'

    # A6: side parvis curb was not trimmed by 439 (only parvis slab was).
    # It extended to z=-4.5 and physically passed through front glazing.
    curbFix=0
    for o in objs:
        if o['parent']!='Place/Retenues' or o['geometry']!='unit_box':continue
        lo,hi=aabb(o)[4:6]
        if lo< -3.70<hi:
            o['size'][2]=round(hi+3.70,5)
            o['position'][2]=round((hi-3.70)/2,5)
            curbFix+=1
    report['counts']['06_curbs_trimmed_before_glass']=curbFix
    assert curbFix>=1, 'Expected real outside curb through glass'

    # A13: central door is OPEN, with no full-height mullions or sill in
    # x ±9.4 m. Preserve all upper facade girders and adjacent bays.
    newDoor=remove(lambda o:o.get('geometry')=='unit_box'
             and o['parent'] in (F+'Mur-rideau V8/Montants raccordes',
                                  F+'Mur-rideau V8/Traverses raccordees',F+'Chassis')
             and abs(o['position'][0])<9.5
             and aabb(o)[2]<3.65
             and -4.45<o['position'][2]<-3.50,
             '13_additional_door_mullions_removed')
    report['issues']['13_door']='ground-level central 19m opening cleared; upper lintel retained'

    # A4: fill holes around existing four speaker pillars with structural
    # support and eliminate ONLY opaque/glazed blocks overlapping speaker
    # volumes at the front; 439 already cut ordinary V17 glazing boxes.
    layout=load(root/'audio/speaker_layout.json') if (root/'audio/speaker_layout.json').exists() else None
    if layout and 'loudspeakers' in layout:
        horns=[sp['position'] for sp in layout['loudspeakers']]
    else:
        horns=[[-30,3.05,-3.62],[-12,3.05,-3.62],[12,3.05,-3.62],[30,3.05,-3.62]]
    assert len(horns)==4
    leftRight=set()
    for x,y,z in horns:
        assert any(abs(x-o['position'][0])<.50
           for o in objs if o['parent']==F+'Colonnade'),('No concrete pilaster for speaker',x)
        leftRight.add(round(x,2))
    report['issues']['04_speakers']='four emitter positions checked against existing concrete colonnade; glass at speaker cuts from 439 retained'
    report['validations'].append('speaker_concrete_pilasters_4')

    # A7: poles in tree root or circular pit (strict 2.25m exclusion).
    trees=[o for o in objs if o.get('parent')=='Nature/Arbres' and o.get('geometry')=='unit_box']
    removedPosts=remove(lambda o:o.get('parent','').startswith('Place/Garde corps')
         and o.get('geometry')=='unit_box'
         and any((o['position'][0]-t['position'][0])**2+
                 (o['position'][2]-t['position'][2])**2<2.25**2 for t in trees),
         '07_tree_pit_posts_removed')
    report['issues']['07_trees']='exclusion radius 2.25m around real trunk anchors, repeated for all trees'

    # A8: actual pool wall, original fresco and water continue to exist.
    # Reduce the blue overlay so immersed stainless remains legible through it.
    waterObjects=[o for o in objs if o['parent']==P+'Eau']
    assert len(waterObjects)==1
    wm=next(m for m in mp['materials'] if m['id']==waterObjects[0]['material'])
    wm['transmission']=.985
    wm['roughness']=.045
    wm['baseColor']=[.28,.64,.69]
    report['issues']['08_immersed_visibility']='water 98.5% transmission, less milkiness; GPU transparency still requires visual verification'

    # A9: controller updated independently to respect TRUE 2.1m pool depth
    # and only the two V8 ladders. Do not create fake geometry here.
    ladderMeshes=[o for o in objs if o['parent'].startswith(P+'Echelles/Inox 316L')]
    assert len(ladderMeshes)==4,('V8 has two actual stainless ladders x two rails',len(ladderMeshes))
    report['issues']['09_pool_navigation']='2 actual ladders x=+24.6, z=-44.05/-19.95; wet area bounded in C++'
    report['validations'].append('real_ladder_rail_meshes_4')

    # A10: retaining original 439 split stair partition. Verify that the
    # retracted center has genuinely removed the original crossing wall.
    assert not any(o['parent']=='Interieur/Vestiaires et douches ouest/Murs'
           and abs(o['position'][0]+40)<.05
           and abs(o['position'][2]+27)<.05 for o in objs)
    report['issues']['10_blocked_stair']='439 split wall retained; staircase handrail closure removed in 440'

    # A11 audio stereo matrix corrected in radio_audio.cpp, no changes in
    # 21-minute recording or any media content.
    report['issues']['11_audio']='stereo matrix channel correction in radio_audio.cpp; 5.1 remains unchanged'

    assert len(set(o['id'] for o in objs))==len(objs)
    assert any('Fresque' in o['parent'] for o in objs)
    assert all(hashlib.sha256((root/p).read_bytes()).hexdigest()==h for p,h in originals.items())
    # No extra duplicate mosaic surfaces and no floor finish across trémies.
    assert len([o for o in objs if o['id']=='v439_entry_mosaic_art'])==1
    assert any('Plages antiderapantes' in o['parent'] for o in objs)

    ip='instances/v440-audit.json';material='materials/v440-audit.json';pbrpath='pbr/v440-audit.json'
    write(root/ip,dict(format='m3d-instances-v1',instances=objs))
    write(root/material,mp);write(root/pbrpath,pbr)
    sec['instances']=[ip];sec['materials']=[material];sec['pbr']=[pbrpath]
    scene['name']='CSE WARP V17.440 — audit des raccordements, sols et acces'
    write(root/'scene-v440-audit.json',scene)
    write(root/'scene-v7-corrections.json',scene)
    report['counts']['total_instances']=len(objs)
    write(root/'reports/v440-audit.json',report)
    print(json.dumps(report,ensure_ascii=False,indent=2))
    return report
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--root',type=Path,required=True)
    build(p.parse_args().root)
