#!/usr/bin/env python3
"""CSE WARP civic landscape V4: scene-only, reproducible high-detail reconstruction.

Input: the regular V3 scene generated by generate.cjs, including the two
authentic JPEG artworks. Output: NEW scene-v4.json, instances/v4.json,
cameras/v4.json, stats/v4-budget.json. Never edits engine files, shaders,
the original instance file, original scene, artworks, or museum fresco.

Design target: x=0 building symmetry axis; 2x oval planting diameter
(not 2x dome height), 2.3x bloom heads, elaborate birch/poplar canopies,
10m heroic allegory, roughly 1.0-1.2 million source triangles.
"""
import argparse, collections, copy, json, math, random
from pathlib import Path

BASE_X=37.0
CENTER_X=0.0
CENTER_Z=52.0
FOOTPRINT_SCALE=2.0
HEIGHT_SCALE=1.15
STATUE_SCALE_XZ=1.20
STATUE_SCALE_Y=1.35
TRIS={'unit_box':12,'unit_sphere':168,'foliage_canopy':324}
RNG=random.Random(0x17B4CA)
TAU=math.tau
GOLDEN=math.pi*(3-math.sqrt(5))

def q(value):
    return round(float(value),3)

def read(path):
    return json.loads(path.read_text(encoding='utf8'))

def write(path,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf8')

def dist(a,b):
    return math.hypot(a,b)

def main(root):
    base_scene=read(root/'scene.json')
    data=copy.deepcopy(read(root/'instances'/'leger.json'))
    instances=data['instances']
    original_count=len(instances)
    assert original_count>=5000, 'Expected geometrically rebuilt V3 baseline'
    original_triangles=sum(TRIS[o['geometry']] for o in instances)
    assert original_triangles>=530000, 'Unexpected low-resolution baseline'
    max_id=len(instances)

    def add(parent,mesh,material,pos,size,angle=0):
        nonlocal max_id
        if not all(math.isfinite(v) for v in pos+size) or min(size)<=0:
            raise ValueError('Invalid generated primitive '+parent)
        max_id+=1
        instances.append({'id':f'v4_{max_id:06d}','parent':parent,
            'geometry':mesh,'material':material,
            'position':[q(x) for x in pos],
            'size':[q(x) for x in size], 'rotationY':q(angle)})

    def sphere(parent,material,x,y,z,sx,sy,sz):
        add(parent,'unit_sphere',material,[x,y,z],[sx,sy,sz])

    def box(parent,material,x,y,z,sx,sy,sz,rotation=0):
        add(parent,'unit_box',material,[x,y,z],[sx,sy,sz],rotation)

    def leaf(parent,material,x,y,z,sx,sy,sz):
        add(parent,'foliage_canopy',material,[x,y,z],[sx,sy,sz])

    # Move BOTH the oval concrete bench and the earthen mound coherently.
    # x axis of the existing historic/fictional building is x=0.
    # No other building, road, pool or fresco is translated.
    for o in instances:
        group=o['parent']
        p=o['position']; s=o['size']
        if group.startswith('Place/Banc ovale béton'):
            p[0]=q(CENTER_X+(p[0]-BASE_X)*FOOTPRINT_SCALE)
            p[2]=q(CENTER_Z+(p[2]-CENTER_Z)*FOOTPRINT_SCALE)
            s[0]=q(s[0]*FOOTPRINT_SCALE)  # tangent length; seat WIDTH unchanged
        elif group.startswith('Place/Butte végétalisée'):
            p[0]=q(CENTER_X+(p[0]-BASE_X)*FOOTPRINT_SCALE)
            p[2]=q(CENTER_Z+(p[2]-CENTER_Z)*FOOTPRINT_SCALE)
            p[1]=q(.32+(p[1]-.32)*HEIGHT_SCALE)
            # Only the DOMED SOIL doubles its x/z dimensions.
            # Flowers remain individual small petals, not 2x colored balls.
            if group=='Place/Butte végétalisée':
                s[0]=q(s[0]*FOOTPRINT_SCALE)
                s[2]=q(s[2]*FOOTPRINT_SCALE)
                s[1]=q(s[1]*HEIGHT_SCALE)
        elif group.startswith('Place/Monument soviétique fictif'):
            p[0]=q(CENTER_X+(p[0]-BASE_X)*STATUE_SCALE_XZ)
            p[2]=q(CENTER_Z+(p[2]-CENTER_Z)*STATUE_SCALE_XZ)
            p[1]=q(.32+(p[1]-.32)*STATUE_SCALE_Y)
            s[0]=q(s[0]*STATUE_SCALE_XZ)
            s[1]=q(s[1]*STATUE_SCALE_Y)
            s[2]=q(s[2]*STATUE_SCALE_XZ)

    # Physical mound top (same half-ellipse as the moved soil mesh).
    def planting_point(i,n,turn=0.0):
        theta=(i+1)*GOLDEN+turn
        radius=math.sqrt((i+.7)/(n+1))*.914
        u,v=radius*math.cos(theta),radius*math.sin(theta)
        x=CENTER_X+28.7*u
        z=CENTER_Z+17.05*v
        y=.32+(1.175*HEIGHT_SCALE)*math.sqrt(max(0,1-radius*radius))
        return x,y,z,theta,radius

    def clear_plinth(x,z):
        return not (abs(x)<4.4 and abs(z-CENTER_Z)<3.65)

    foliage_materials=['cse_leaf_olive','prp_foliage','cse_leaf_gold']
    flower_materials=['cse_flower_red','cse_flower_gold',
                     'cse_flower_purple','cse_flower_blue']

    # ~400 new low, small-leaved clusters support the 4x planting surface.
    # Variance in height, radial position, and orientation avoids tiling rows.
    cover_added=0
    for i in range(438):
        x,y,z,a,_=planting_point(i,438,turn=.43)
        if not clear_plinth(x,z):
            continue
        radius=.34+.19*RNG.random()
        material=foliage_materials[(i//14+i%7)%3]
        leaf('Place/Butte végétalisée/V4 Couvre-sol',material,
            x,y+.08,z,
            radius*(1.5+.35*RNG.random()),.19+.18*RNG.random(),
            radius*(1.2+.5*RNG.random()))
        cover_added+=1

    # More than double the bloom count, now 6 separate petals / flower.
    # Individual green leaves and stamens read as flowers in the close-up
    # without resizing the original petals.
    heads_added=0
    for i in range(240):
        x,y,z,a,_=planting_point(i,240,turn=1.37)
        if not clear_plinth(x,z):
            continue
        h=.27+.21*RNG.random()
        # Soft region-based palette: beds of colors rather than pixel confetti.
        palette_index=int((a%TAU)/(TAU/4))
        color=flower_materials[(palette_index+(i//19)%2)%4]
        box('Place/Butte végétalisée/V4 Tiges','cse_leaf_olive',
            x,y+h*.51,z,.028,h,.028)
        for j in range(6):
            angle=a+j*TAU/6
            radial=.12+.025*RNG.random()
            sphere('Place/Butte végétalisée/V4 Pétales',color,
                x+radial*math.cos(angle),y+h+.012,
                z+radial*math.sin(angle),.17,.065,.12)
        sphere('Place/Butte végétalisée/V4 Pistils',
               'cse_flower_gold',x,y+h+.03,z,.09,.10,.09)
        for j in (-1,1):
            angle=a+j*.89
            sphere('Place/Butte végétalisée/V4 Feuilles','cse_leaf_olive',
                x+.18*math.cos(angle),y+.13,z+.18*math.sin(angle),
                .27,.07,.18)
        heads_added+=1

    # Real extra branching and multiple small crown silhouettes on all trees.
    # Distinguish birch (wide asymmetric twigs) vs poplar (vertical columns).
    trunks=[o for o in instances if o['parent']=='Nature/Arbres']
    assert len(trunks)==26, f'Tree baseline changed: {len(trunks)}'
    tree_crown_added=0
    for i,trunk in enumerate(trunks):
        x,base,z=trunk['position']
        h=trunk['size'][1]/.8
        birch=i%3==0
        is_near=(abs(x)<73 and -1<z<98)
        count=11 if is_near else 7
        bark='cse_birch_bark' if birch else 'prp_bark_wet'
        green='prp_foliage' if birch else ('cse_leaf_gold' if i%7==0 else 'cse_leaf_olive')
        for j in range(count):
            a=(i*.33+j*GOLDEN+RNG.uniform(-.19,.19))
            radius=(1.36 if birch else .74)+(.20*RNG.random())
            level=h*(.66+.31*(j+.5)/count)
            dx=radius*math.cos(a);dz=radius*math.sin(a)
            leaf('Nature/Arbres/V4 Houppier fin',green,
                x+dx,level,z+dz,
                (.72 if birch else .60)+.37*RNG.random(),
                (1.34 if birch else 2.10)+.8*RNG.random(),
                (.69 if birch else .62)+.34*RNG.random())
            tree_crown_added+=1
            # Intertwined twig from structural branch to canopy lobe.
            if j%2==0:
                box('Nature/Arbres/V4 Rameaux',bark,
                    x+dx*.55,level-.30,z+dz*.55,
                    .34+.21*RNG.random(),.052,.055,math.degrees(a))
        # A thin separate crown leaf-facet silhouette adds visible
        # outer texture without uniformly thickening the complete tree.
        for j in range(6):
            a=i*.39+j*GOLDEN
            radius=1.25 if birch else .73
            y=h*(.74+.035*j)
            sphere('Nature/Arbres/V4 Feuilles séparées',green,
                x+radius*math.cos(a),y,z+radius*math.sin(a),
                .29,.53 if birch else .74,.21)

    # Statue refinement: small discreet high-frequency geometry around
    # hands, hair, clothes, and star; NOT another row of torso beads.
    # Coordinates refer to the NEW monument, after the translation/scale.
    monument='Place/Monument soviétique fictif'
    bronze='cse_monument_bronze'
    for i,person_x in enumerate((-0.79*STATUE_SCALE_XZ, .76*STATUE_SCALE_XZ)):
        # Low-relief seams on the sides of clothing, not banded on the torso.
        for j in range(10):
            y=(4.08+j*.105-.32)*STATUE_SCALE_Y+.32
            sign=-1 if j%2 else 1
            sphere(monument+'/V4 Drapé en relief',bronze,
                person_x+sign*(.39+.05*RNG.random()),
                y,CENTER_Z+.24*STATUE_SCALE_XZ,
                .07,.22,.058)
        # Back-hair and cheek profile details, each tiny and localized.
        for j in range(8):
            a=j*TAU/8
            yy=(5.67-.32)*STATUE_SCALE_Y+.32
            sphere(monument+'/V4 Coiffure et profil',bronze,
                person_x+.19*math.cos(a), yy+.25*math.sin(a),
                CENTER_Z-.30,.085,.14,.084)
        # Fingers separate near the actual hand endpoints, subdued.
        hand_x=person_x+((-1.40 if i==0 else 1.00)*STATUE_SCALE_XZ)
        hand_y=(4.63 if i==0 else 6.65)
        hand_y=.32+(hand_y-.32)*STATUE_SCALE_Y
        for j in range(5):
            sphere(monument+'/V4 Main et doigts',bronze,
                hand_x+(j-2)*.046, hand_y-.11, CENTER_Z+.04,
                .041,.16,.06)

    # Delicate thin metal relief on plinth and optional inscriptions.
    for side in (-1,1):
        for j in range(7):
            box(monument+'/V4 Relief du socle','prp_steel_rusted',
                side*(2.0+j*.11),1.6+j*.10,
                CENTER_Z+2.15,.038,.16,.038)

    # Previous cameras/scene remain immutable; new curated V4 viewpoints.
    view=copy.deepcopy(read(root/'cameras'/'views.json'))
    view['cameras']=[
      {'id':'v4_face','name':'01 · Façade et butte centrées',
       'position':[0,10.5,119],'target':[0,8,-2],'fovDegrees':65},
      {'id':'v4_place','name':'02 · Place végétale et monument, angle est',
       'position':[55,15,99],'target':[0,5.2,48],'fovDegrees':66},
      {'id':'v4_monument','name':'03 · Monument au centre du massif',
       'position':[16,5.0,80],'target':[0,7.3,52],'fovDegrees':51},
      {'id':'v4_fleurs','name':'04 · Détails floraux et couvert végétal',
       'position':[28,2.45,76],'target':[17,1.35,65],'fovDegrees':59},
      {'id':'v4_arbres','name':'05 · Peupliers et bouleaux détaillés',
       'position':[-31,3.4,21],'target':[-43,9,34],'fovDegrees':57},
      {'id':'v4_aerienne','name':'06 · Axe du palais vu du ciel',
       'position':[77,67,119],'target':[0,5,24],'fovDegrees':66},
      {'id':'v4_piscine','name':'07 · Piscine olympique en soirée',
       'position':[32.5,6.05,-19],'target':[0,1.1,-33],'fovDegrees':67},
      {'id':'v4_hall','name':'08 · Hall et fresque originelle',
       'position':[-15,10.35,-11.6],'target':[-15,10.35,-18.0],'fovDegrees':67},
    ]
    scene=copy.deepcopy(base_scene)
    scene['name']='CSE WARP V17.370 — Palais fictif et paysage monumental V4 1.1M'
    scene['sectors'][0]['instances']=['instances/v4.json']
    scene['sectors'][0]['cameras']=['cameras/v4.json']
    data['instances']=instances
    write(root/'instances'/'v4.json',data)
    write(root/'cameras'/'v4.json',view)
    write(root/'scene-v4.json',scene)

    # Model source triangle count is exact for this unchanged engine's mesh
    # generation: box=12, UV sphere (12x8 with poles)=168, foliage=(18x9
    # with poles)+36 leaf facets=324. Submitted camera-dependent triangles
    # may be less due to GPU culling and LOD.
    original_categories={
       'monument':'Place/Monument soviétique fictif',
       'butte_fleurs':'Place/Butte végétalisée',
       'arbres':'Nature/Arbres',
       'banc_ovale':'Place/Banc ovale béton',
    }
    group_counts={}
    for label,prefix in original_categories.items():
        selected=[o for o in instances if o['parent'].startswith(prefix)]
        group_counts[label]={'objects':len(selected),
               'triangles':sum(TRIS[x['geometry']] for x in selected)}
    triangles=sum(TRIS[o['geometry']] for o in instances)
    assert 1_000_000<=triangles<=1_200_000, f'Unexpected target budget {triangles}'
    assert abs(next(o for o in instances if o['parent']=='Place/Butte végétalisée')['position'][0])<.001
    assert next(o for o in instances if o['parent']=='Place/Butte végétalisée')['size'][0]==58
    assert len([o for o in instances if o['parent']=='Place/Banc ovale béton/Assise'])==96
    assert len([o for o in instances if o['material']=='cse_personnage_facade'])==1
    assert len([o for o in instances if o['material']=='cse_energetik_fresco'])==1
    assert len({o['id'] for o in instances})==len(instances)
    materials={m['id'] for m in read(root/'materials'/'pripyat-reuse.json')['materials']}
    assert all(o['material'] in materials and o['geometry'] in TRIS for o in instances)
    out={'version':'V4','motor':'frozen V17.370','building_axis_x':0,
         'mound_center_xyz':[CENTER_X,.32,CENTER_Z],
         'mound_diameter_m':[58,34.4],
         'oval_bench_radii_m':[32.9,21.0],
         'footprint_scale':2,
         'original_objects':original_count,'v4_objects':len(instances),
         'original_triangles':original_triangles,'v4_triangles':triangles,
         'triangles_added':triangles-original_triangles,
         'new_cover_plants':cover_added,'new_flower_heads':heads_added,
         'extra_tree_canopy_lobes':tree_crown_added,
         'groups':group_counts,
         'remarks':'Source geometry triangles, not visible/submitted triangles after frustum culling and LOD'}
    write(root/'stats'/'v4-budget.json',out)
    print(json.dumps(out,ensure_ascii=False,indent=2),flush=True)

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--root',type=Path,default=Path(__file__).parent)
    main(parser.parse_args().root.resolve())
