; MOTEUR3D CPC6128 / RASTERISATION Z80 / MODE 0 / V0.1.0
; BRANCHE RASTER — 19 OCTOBRE 2026
; Source demonstrative RASM / WinAPE compatible (ASSEMBLAGE NON TESTE).
; 160x200 / 16 encres / deux pixels par octet (80 octets par ligne).
; 24 TRIANGLES PLEINS sans textures, sans Z-buffer, tri painter offline.
; 8 orientations 3D preprojetees hors CPC, 2 images dans chacune des
; banques RAM 4, 5, 6, 7. Le CPC rasterise vraiment les triangles :
; arêtes x.8 en virgule fixe, spans horizontaux, ecriture ecran Mode 0.
; Vitesse REELLE INCONNUE : aucune mesure emulateur ou cycle trace.
;
; LOAD &8000 depuis BASIC, puis CALL &8000. DI / firmware et ROMs OFF.
; Pour quitter : RESET matériel. Pas d'appels OS pendant l'animation.
; La logique de projection 3D se trouve dans la generation des tables :
; les matrices 3D ne sont PAS recalculees sur ce Z80.
;
; MEMOIRE CPC6128:
;   &0000-&3FFF: RAM base, buffers de spans &3000 / &3100, pile &3FF0
;   &4000-&7FFF: banque RAM4-7 commute par GA C4..C7, 2 poses / banque
;   &8000-&BFFF: programme + 8 poses preprojetees + adresses ecran
;   &C000-&FFFF: ecran Mode 0 (RAM de base)
; 128 Ko accessibles par bancs ; la demo n'en remplit pas la totalite.

        ORG &8000
SCENE_BYTES EQU 528             ; 24 triangles x 22 bytes
PAIR_BYTES  EQU 1056            ; 2 poses par banque
TRI_COUNT   EQU 24
SpanLeft    EQU &3000
SpanRight   EQU &3100

Start:
        DI
        LD SP,&3FF0
        LD BC,&7F00
        LD A,&8C                  ; mode 0, deux ROMs desactivees
        OUT (C),A
        CALL InitPalette
        CALL CopyBankedPoses
        XOR A
        LD (FrameIndex),A

FrameLoop:
        CALL ClearBackdrop
        LD A,(FrameIndex)
        SRL A
        ADD A,&C4
        CALL BankSelect
        LD IX,&4000
        LD A,(FrameIndex)
        AND 1
        JR Z,SelectFirst
        LD DE,SCENE_BYTES
        ADD IX,DE
SelectFirst:
        LD A,TRI_COUNT
        LD (TrianglesLeft),A

RasterNext:
        CALL RasterTriangle
        LD DE,22
        ADD IX,DE
        LD A,(TrianglesLeft)
        DEC A
        LD (TrianglesLeft),A
        JR NZ,RasterNext

        LD A,(FrameIndex)
        INC A
        AND 7
        LD (FrameIndex),A
        JR FrameLoop

; A=&C4..&C7. Banque etendue active sous &4000-&7FFF.
; BC doit toujours viser le port Gate Array &7Fxx.
BankSelect:
        PUSH BC
        LD BC,&7F00
        OUT (C),A
        POP BC
        RET

InitPalette:
        LD HL,HardwareColours
        LD E,0
PaletteNext:
        LD BC,&7F00
        LD A,E
        OUT (C),A
        LD A,(HL)
        OUT (C),A
        INC HL
        INC E
        LD A,E
        CP 16
        JR NZ,PaletteNext
        RET

; Copier la geometrie pre-projetee dans chaque banque 4..7.
; Toutes les autres routines continuent dans &8000-&BFFF (RAM fixe).
CopyBankedPoses:
        LD HL,Pose0
        LD A,&C4
        LD (InitBank),A
CopyNextBank:
        LD A,(InitBank)
        CALL BankSelect
        LD DE,&4000
        LD BC,PAIR_BYTES
        LDIR
        LD A,(InitBank)
        INC A
        LD (InitBank),A
        CP &C8
        JR NZ,CopyNextBank
        LD A,&C4
        CALL BankSelect
        RET

; Mode 0 solid pattern for identical left & right pixel:
; pen1=&03, pen2=&30, pen3=&33, pen4=&0C, etc.
; Garde le fond bicolore sky/ground. Refaite par image.
ClearBackdrop:
        LD IX,ScreenLines
        LD B,200
ClearNextRow:
        LD L,(IX+0)
        LD H,(IX+1)
        LD A,B
        CP 101
        LD A,&30                   ; ground pen 2
        JR C,UseGround
        LD A,&03                   ; sky pen 1
UseGround:
        LD C,80
FillClearRow:
        LD (HL),A
        INC HL
        DEC C
        JR NZ,FillClearRow
        INC IX
        INC IX
        DJNZ ClearNextRow
        RET

; Triangle in IX, record structure:
;   +0 ink (packed mode0 pen), +1 ymin, +2 ymax excl., +3 reserve
;   +4 edge 0, +10 edge 1, +16 edge 2 (6 bytes each):
;     ystart,yend,xstart lo,hi,slope lo,hi
; Each edge is stepped in signed 8.8 X using one ADD HL,DE per scanline.
RasterTriangle:
        LD A,(IX+0)
        LD (Ink),A
        LD A,(IX+2)
        LD B,A
        LD A,(IX+1)
        LD (CurrentY),A
        LD C,A
        LD A,B
        SUB C
        RET Z
        LD B,A
        LD L,C
        LD H,&30                  ; SpanLeft[y]
        LD D,&31
        LD E,C                   ; SpanRight[y], DE points same row
ClearSpans:
        LD A,&FF
        LD (HL),A
        XOR A
        LD (DE),A
        INC HL
        INC DE
        DJNZ ClearSpans

        PUSH IX
        POP HL
        LD DE,4
        ADD HL,DE
        CALL StepEdge
        PUSH IX
        POP HL
        LD DE,10
        ADD HL,DE
        CALL StepEdge
        PUSH IX
        POP HL
        LD DE,16
        ADD HL,DE
        CALL StepEdge

DrawSpans:
        LD A,(CurrentY)
        LD B,A
        LD A,(IX+2)
        CP B
        RET Z
        RET C
        LD L,B
        LD H,&30
        LD A,(HL)
        CP &FF
        JR Z,AdvanceY
        LD (LeftByte),A
        LD H,&31
        LD A,(HL)
        LD (RightByte),A
        LD B,A
        LD A,(LeftByte)
        CP B
        JR C,SpanGood
        JR Z,SpanGood
        JR AdvanceY
SpanGood:
        LD A,(CurrentY)
        LD L,A
        LD H,0
        ADD HL,HL
        LD DE,ScreenLines
        ADD HL,DE
        LD E,(HL)
        INC HL
        LD D,(HL)
        EX DE,HL
        LD A,(LeftByte)
        LD E,A
        LD D,0
        ADD HL,DE
        LD A,(RightByte)
        LD B,A
        LD A,(LeftByte)
        LD C,A
        LD A,B
        SUB C
        INC A
        LD B,A
        LD A,(Ink)
WriteSpan:
        LD (HL),A
        INC HL
        DJNZ WriteSpan

AdvanceY:
        LD A,(CurrentY)
        INC A
        LD (CurrentY),A
        JR DrawSpans

; HL points to 6-byte edge: y0,y1,x0.8.8,dx/dy.8.8.
; For every scanline update min and max byte-column X.
StepEdge:
        LD A,(HL)
        LD (EdgeY),A
        INC HL
        LD A,(HL)
        LD (EdgeEnd),A
        INC HL
        LD E,(HL)
        INC HL
        LD D,(HL)
        LD (EdgeX),DE
        INC HL
        LD E,(HL)
        INC HL
        LD D,(HL)
        LD (StepX),DE
EdgeLoop:
        LD A,(EdgeY)
        LD B,A
        LD A,(EdgeEnd)
        CP B
        RET Z
        RET C
        LD L,B
        LD H,&30
        LD A,(EdgeX+1)           ; signed fixed high byte, clamped by pose tool
        CP (HL)
        JR NC,EdgeNoLeft
        LD (HL),A
EdgeNoLeft:
        LD H,&31
        LD A,(EdgeX+1)
        LD B,(HL)
        CP B
        JR C,EdgeNoRight
        LD (HL),A
EdgeNoRight:
        LD HL,(EdgeX)
        LD DE,(StepX)
        ADD HL,DE
        LD (EdgeX),HL
        LD A,(EdgeY)
        INC A
        LD (EdgeY),A
        JR EdgeLoop

FrameIndex:     DB 0
InitBank:       DB 0
TrianglesLeft:  DB 0
CurrentY:       DB 0
LeftByte:       DB 0
RightByte:      DB 0
Ink:            DB 0
EdgeY:          DB 0
EdgeEnd:        DB 0
EdgeX:          DW 0
StepX:          DW 0

